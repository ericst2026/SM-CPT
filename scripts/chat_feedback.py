#!/usr/bin/env python3
"""Manually test a model, give feedback, and turn feedback into training data.

    python scripts/chat_feedback.py                                   # web UI (http://127.0.0.1:7860), base model
    python scripts/chat_feedback.py --model runs/lora_r16/adapter     # web UI with an adapter
    python scripts/chat_feedback.py --cli --model runs/lora_r16       # terminal chat
    python scripts/chat_feedback.py --base models/Qwen3-0.6B \\
        --model runs/cpt_qwen06b_r64_300mb/epoch1/adapter             # apply an adapter to a different base
    python scripts/chat_feedback.py --stats                           # feedback summary
    python scripts/chat_feedback.py --export                          # -> data/feedback/feedback_{sft,dpo}.jsonl

Web UI tabs
  Chat     pick model (base or any runs/*/adapter), learner level (system prompt), thinking mode,
           sampling; chat multi-turn; then rate the LAST answer: verdict, 1-5 rating, tags, comment and an
           optional corrected answer -> "Save feedback" appends to data/feedback/feedback.jsonl
  Review   step through eval_results/<tag>/open_qa_predictions.jsonl (answers generated by eval_model.py)
           next to the dataset reference, and rate / correct them the same way
  Export   statistics + export feedback to SFT / DPO files

Use the exported SFT file in the next training round:
    python scripts/train_lora.py --init-adapter runs/lora_r16/adapter --data data/final/sft_train.jsonl \\
        --extra-data data/feedback/feedback_sft.jsonl --max-samples 20000 --run-name lora_r16_fb1
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
import threading

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import torch  # noqa: E402

from ai_qa_data.taxonomy import LEVELS  # noqa: E402
from ai_qa_train.common import (DEFAULT_BASE, ROOT, load_model, load_tokenizer, render, resolve_adapter,  # noqa: E402
                                split_thinking)
from ai_qa_train.feedback import FEEDBACK_FILE, TAGS, export, load_feedback, save_feedback, stats  # noqa: E402


class Engine:
    """Holds one loaded model; can switch between base / adapters.

    `base` overrides the base model an adapter is applied to (default: the one in its adapter_config.json),
    e.g. to put a CPT adapter trained on Qwen3-0.6B-Base onto the Qwen3-0.6B chat model."""

    def __init__(self, model_path: str | None, load_4bit: bool = False, base: str | None = None):
        self.lock = threading.Lock()
        self.load_4bit = load_4bit
        self.base = base
        self.name = None
        self.load(model_path)

    def load(self, model_path: str | None, base: str | None = ...):
        if base is not ...:
            self.base = base
        base_path, adapter = resolve_adapter(model_path or self.base)
        if adapter and self.base:
            base_path = self.base
        if getattr(self, "model", None) is not None:
            del self.model
            torch.cuda.empty_cache()
        self.tok = load_tokenizer(base_path)
        self.model = load_model(base_path, adapter=adapter, quantize_4bit=self.load_4bit, merge=True)
        self.loaded = os.path.relpath(adapter or base_path, ROOT)
        self.name =(f"{os.path.relpath(adapter, ROOT)} @ {os.path.relpath(base_path, ROOT)}" if adapter
                     else os.path.relpath(base_path, ROOT))
        return self.name

    def stream(self, messages, enable_thinking=False, temperature=0.7, top_p=0.8, max_new_tokens=1024,
               repetition_penalty=1.05):
        from transformers import TextIteratorStreamer

        prompt = render(self.tok, messages, add_generation_prompt=True, enable_thinking=enable_thinking)
        enc = self.tok(prompt, return_tensors="pt", add_special_tokens=False).to(self.model.device)
        streamer = TextIteratorStreamer(self.tok, skip_prompt=True, skip_special_tokens=True)
        gk = dict(**enc, max_new_tokens=int(max_new_tokens), streamer=streamer, pad_token_id=self.tok.pad_token_id,
                  repetition_penalty=repetition_penalty)
        if temperature > 0:
            gk.update(do_sample=True, temperature=temperature, top_p=top_p, top_k=20)
        else:
            gk.update(do_sample=False, temperature=None, top_p=None, top_k=None)
        with self.lock:
            th = threading.Thread(target=self.model.generate, kwargs=gk)
            th.start()
            text = ""
            for piece in streamer:
                text += piece
                yield text
            th.join()


def list_models() -> list[str]:
    found = sorted(glob.glob(os.path.join(ROOT, "runs", "*", "adapter")) +
                   glob.glob(os.path.join(ROOT, "runs", "*", "epoch*", "adapter")) +
                   glob.glob(os.path.join(ROOT, "runs", "*", "checkpoint-*")) +
                   glob.glob(os.path.join(ROOT, "runs", "*", "merged")))
    return [NO_ADAPTER] + [os.path.relpath(p, ROOT) for p in found]


NO_ADAPTER = "No adapter (base model only)"
ADAPTER_BASE = "(adapter's own base)"


def list_base_models() -> list[str]:
    found = sorted(os.path.dirname(p) for p in glob.glob(os.path.join(ROOT, "models", "*", "config.json"))
                   if any(a.endswith("ForCausalLM") for a in json.load(open(p)).get("architectures", [])))
    return [ADAPTER_BASE] + [os.path.relpath(p, ROOT) for p in found]


def list_prediction_files() -> list[str]:
    return [os.path.relpath(p, ROOT) for p in sorted(glob.glob(os.path.join(ROOT, "eval_results", "*",
                                                                           "open_qa_predictions.jsonl")))]


