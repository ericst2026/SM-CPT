def build_ui(engine: Engine):
    import gradio as gr

    level_names = list(LEVELS)

    def sys_for(level):
        return LEVELS[level]["system"] if level in LEVELS else ""

    # ---------- chat callbacks ----------
    def respond(user_msg, history, system, thinking, temperature, top_p, max_tokens):
        history = history or []
        if not user_msg.strip():
            yield history, "", "", ""
            return
        convo = ([{"role": "system", "content": system}] if system.strip() else []) + \
                [{"role": m["role"], "content": m["content"]} for m in history] + \
                [{"role": "user", "content": user_msg}]
        history = history + [{"role": "user", "content": user_msg}, {"role": "assistant", "content": ""}]
        think, ans = "", ""
        for text in engine.stream(convo, thinking, temperature, top_p, max_tokens):
            think, ans = split_thinking(text)
            history[-1]["content"] = ans or "…thinking…"
            yield history, "", think, ans
        history[-1]["content"] = ans
        yield history, "", think, ans

    def save_chat_feedback(history, system, level, thinking, temperature, think, verdict, rating, tags, comment,
                           correction):
        if not history or history[-1]["role"] != "assistant":
            return "Nothing to rate yet.", gr.update()
        msgs = ([{"role": "system", "content": system}] if system.strip() else []) + \
               [{"role": m["role"], "content": m["content"]} for m in history[:-1]]
        resp = history[-1]["content"]
        rec = save_feedback({
            "model": engine.name, "origin": "chat", "level": level, "system": system,
            "enable_thinking": bool(thinking), "temperature": temperature,
            "messages": msgs, "response": resp, "thinking": think or None,
            "rating": int(rating), "verdict": verdict, "tags": tags or [], "comment": comment or "",
            "correction": (correction or "").strip() if (correction or "").strip() != resp.strip() else None,
            "reference": None})
        return f"Saved feedback {rec['id']} ({verdict}, {rating}/5) -> {os.path.relpath(FEEDBACK_FILE, ROOT)}", ""

    def switch_model(choice, base_choice):
        path = None if choice == NO_ADAPTER else os.path.join(ROOT, choice)
        base = None if base_choice == ADAPTER_BASE else os.path.join(ROOT, base_choice)
        name = engine.load(path, base=base)
        return f"Loaded: `{name}`", []

    # ---------- review callbacks ----------
    def load_review(path):
        rows = [json.loads(l) for l in open(os.path.join(ROOT, path), encoding="utf-8") if l.strip()]
        done = {(r.get("review_of")) for r in load_feedback()}
        rows = [r for r in rows if f"{path}#{r['id']}" not in done]
        return rows, 0, *show_review(rows, 0)

    def show_review(rows, i):
        if not rows or i >= len(rows):
            return "No (more) items.", "", "", "", ""
        r = rows[i]
        head = (f"**{i + 1}/{len(rows)}** · level `{r['level']}` · topics {r.get('topics')} · "
                f"ROUGE-L {r.get('rougeL')} · FK grade {r.get('fk_grade')}")
        return head, r["question"], r["answer"], r.get("reference", ""), r["answer"]

    def save_review(rows, i, path, verdict, rating, tags, comment, correction):
        if not rows or i >= len(rows):
            return i, "Nothing to save.", *show_review(rows, i)
        r = rows[i]
        corr = (correction or "").strip()
        save_feedback({
            "model": path.split("/")[1] if "/" in path else path, "origin": "eval_review", "review_of": f"{path}#{r['id']}",
            "level": r["level"], "system": r.get("system") or LEVELS[r["level"]]["system"], "enable_thinking": False,
            "temperature": 0.0, "messages": [{"role": "user", "content": r["question"]}], "response": r["answer"],
            "thinking": r.get("thinking") or None, "rating": int(rating), "verdict": verdict, "tags": tags or [],
            "comment": comment or "", "correction": corr if corr and corr != r["answer"].strip() else None,
            "reference": r.get("reference")})
        return i + 1, f"Saved review of {r['id']}", *show_review(rows, i + 1)

    def skip_review(rows, i):
        return i + 1, *show_review(rows, i + 1)

    # ---------- layout ----------
    with gr.Blocks(title="AI tutor - test & feedback") as ui:
        gr.Markdown("## AI tutor (Qwen3 + LoRA) — manual testing & feedback")
        with gr.Tab("Chat"):
            with gr.Row():
                models = list_models()
                model_dd = gr.Dropdown(models, value=engine.loaded if engine.loaded in models else NO_ADAPTER,
                                       label="Adapter", scale=3)
                bases = list_base_models()
                cur_base = os.path.relpath(engine.base, ROOT) if engine.base else ADAPTER_BASE
                base_dd = gr.Dropdown(bases, value=cur_base if cur_base in bases else ADAPTER_BASE,
                                      label="Base model (the adapter is applied to it)", scale=2)
                load_btn = gr.Button("Load model", scale=1)
                model_status = gr.Markdown(f"Loaded: `{engine.name}`")
            with gr.Row():
                with gr.Column(scale=3):
                    chat = gr.Chatbot(height=480, label="Conversation")
                    user = gr.Textbox(placeholder="Ask an AI question… (Enter to send)", label="Message")
                    with gr.Row():
                        send = gr.Button("Send", variant="primary")
                        clear = gr.Button("New conversation")
                    with gr.Accordion("Thinking (when thinking mode is on)", open=False):
                        think_box = gr.Textbox(lines=6, label="Reasoning trace", interactive=False)
                with gr.Column(scale=2):
                    level = gr.Dropdown(level_names, value="high_school", label="Learner level")
                    system = gr.Textbox(sys_for("high_school"), lines=4, label="System prompt (editable)")
                    thinking = gr.Checkbox(False, label="Thinking mode (<think>)")
                    temperature = gr.Slider(0, 1.5, 0.7, step=0.05, label="Temperature (0 = greedy)")
                    top_p = gr.Slider(0.1, 1.0, 0.8, step=0.05, label="top-p")
                    max_tokens = gr.Slider(64, 4096, 1024, step=64, label="Max new tokens")
            gr.Markdown("### Feedback on the last answer")
            with gr.Row():
                verdict = gr.Radio(["good", "neutral", "bad"], value="good", label="Verdict")
                rating = gr.Slider(1, 5, 4, step=1, label="Rating")
                tags = gr.CheckboxGroup(TAGS, label="Tags")
            comment = gr.Textbox(lines=2, label="Comment")
            last_answer = gr.Textbox(visible=False)
            correction = gr.Textbox(lines=6, label="Corrected / ideal answer (optional — edit the model answer)")
            with gr.Row():
                copy_btn = gr.Button("Copy model answer into correction box")
                save_btn = gr.Button("Save feedback", variant="primary")
            fb_status = gr.Markdown()

            level.change(sys_for, level, system)
            send_args = dict(fn=respond, inputs=[user, chat, system, thinking, temperature, top_p, max_tokens],
                             outputs=[chat, user, think_box, last_answer])
            send.click(**send_args)
            user.submit(**send_args)
            clear.click(lambda: ([], "", "", ""), None, [chat, think_box, last_answer, correction])
            copy_btn.click(lambda a: a, last_answer, correction)
            save_btn.click(save_chat_feedback,
                           [chat, system, level, thinking, temperature, think_box, verdict, rating, tags, comment,
                            correction], [fb_status, correction])
            load_btn.click(switch_model, [model_dd, base_dd], [model_status, chat])

        with gr.Tab("Review eval answers"):
            rows_state, idx_state = gr.State([]), gr.State(0)
            with gr.Row():
                pred_dd = gr.Dropdown(list_prediction_files(), label="open_qa_predictions.jsonl (from eval_model.py)",
                                      scale=4)
                load_pred = gr.Button("Load", scale=1)
            head = gr.Markdown()
            q_box = gr.Textbox(label="Question", lines=3, interactive=False)
            with gr.Row():
                a_box = gr.Textbox(label="Model answer", lines=10, interactive=False)
                ref_box = gr.Textbox(label="Dataset reference", lines=10, interactive=False)
            with gr.Row():
                r_verdict = gr.Radio(["good", "neutral", "bad"], value="good", label="Verdict")
                r_rating = gr.Slider(1, 5, 4, step=1, label="Rating")
                r_tags = gr.CheckboxGroup(TAGS, label="Tags")
            r_comment = gr.Textbox(lines=2, label="Comment")
            r_corr = gr.Textbox(lines=6, label="Corrected answer (pre-filled with the model answer)")
            with gr.Row():
                r_skip = gr.Button("Skip")
                r_save = gr.Button("Save & next", variant="primary")
            r_status = gr.Markdown()
            load_pred.click(load_review, pred_dd, [rows_state, idx_state, head, q_box, a_box, ref_box, r_corr])
            r_save.click(save_review, [rows_state, idx_state, pred_dd, r_verdict, r_rating, r_tags, r_comment, r_corr],
                         [idx_state, r_status, head, q_box, a_box, ref_box, r_corr])
            r_skip.click(skip_review, [rows_state, idx_state], [idx_state, head, q_box, a_box, ref_box, r_corr])

        with gr.Tab("Export"):
            st = gr.JSON(label="Feedback statistics")
            with gr.Row():
                refresh = gr.Button("Refresh stats")
                exp = gr.Button("Export to SFT / DPO files", variant="primary")
            exp_out = gr.JSON(label="Export result")
            gr.Markdown("Train on it: `python scripts/train_lora.py --init-adapter <adapter> "
                        "--extra-data data/feedback/feedback_sft.jsonl ...`")
            refresh.click(lambda: stats(), None, st)
            exp.click(lambda: export(), None, exp_out)
            ui.load(lambda: stats(), None, st)
    return ui


