CLI_HELP = """commands:
  /level <name>   set learner level ({levels})
  /think          toggle thinking mode          /temp <t>   set temperature
  /rate           rate the last answer (verdict, rating, tags, comment, correction)
  /reset          new conversation              /stats      feedback statistics
  /export         export feedback -> SFT/DPO    /quit"""


def run_cli(engine: Engine):
    level, thinking, temp = "high_school", False, 0.7
    history: list[dict] = []
    print(CLI_HELP.format(levels=", ".join(LEVELS)))
    print(f"model: {engine.name}")
    while True:
        try:
            line = input(f"\n[{level}{' think' if thinking else ''}] you> ").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if not line:
            continue
        if line.startswith("/"):
            cmd, _, arg = line.partition(" ")
            if cmd == "/quit":
                break
            elif cmd == "/level" and arg in LEVELS:
                level, history = arg, []
                print("level set; conversation reset")
            elif cmd == "/think":
                thinking = not thinking
                print("thinking", thinking)
            elif cmd == "/temp":
                temp = float(arg)
            elif cmd == "/reset":
                history = []
            elif cmd == "/stats":
                print(json.dumps(stats(), indent=2))
            elif cmd == "/export":
                print(json.dumps(export(), indent=2))
            elif cmd == "/rate":
                if not history or history[-1]["role"] != "assistant":
                    print("nothing to rate")
                    continue
                verdict = input("verdict [good/neutral/bad]: ").strip() or "neutral"
                rating = int(input("rating 1-5: ").strip() or 3)
                tags = [t.strip() for t in input(f"tags (comma; {', '.join(TAGS)}): ").split(",") if t.strip()]
                comment = input("comment: ").strip()
                print("corrected answer (end with an empty line, leave empty to skip):")
                lines = []
                while True:
                    ln = input()
                    if not ln:
                        break
                    lines.append(ln)
                rec = save_feedback({
                    "model": engine.name, "origin": "chat", "level": level, "system": LEVELS[level]["system"],
                    "enable_thinking": thinking, "temperature": temp, "messages": history[:-1],
                    "response": history[-1]["content"], "thinking": None, "rating": rating, "verdict": verdict,
                    "tags": tags, "comment": comment, "correction": "\n".join(lines) or None, "reference": None})
                print("saved", rec["id"])
            else:
                print(CLI_HELP.format(levels=", ".join(LEVELS)))
            continue
        history.append({"role": "user", "content": line})
        convo = [{"role": "system", "content": LEVELS[level]["system"]}] + history
        print("model> ", end="", flush=True)
        shown = 0
        text = ""
        for text in engine.stream(convo, thinking, temp, 0.8, 1024):
            print(text[shown:], end="", flush=True)
            shown = len(text)
        print()
        history.append({"role": "assistant", "content": split_thinking(text)[1]})


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", default=None, help="adapter / run dir / merged model; default = --base or Qwen3-1.7B")
    ap.add_argument("--base", default=None,
                    help="base model to apply the adapter to, overriding its adapter_config.json "
                         "(e.g. models/Qwen3-0.6B for a CPT adapter trained on Qwen3-0.6B-Base)")
    ap.add_argument("--load-4bit", action="store_true")
    ap.add_argument("--cli", action="store_true", help="terminal chat instead of the web UI")
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=7860)
    ap.add_argument("--share", action="store_true", help="public gradio link (exposes the model!)")
    ap.add_argument("--stats", action="store_true")
    ap.add_argument("--export", action="store_true")
    args = ap.parse_args()

    if args.stats:
        print(json.dumps(stats(), indent=2))
        return
    if args.export:
        print(json.dumps(export(), indent=2))
        return
    base = os.path.abspath(args.base) if args.base else None
    engine = Engine(args.model or base or DEFAULT_BASE, args.load_4bit, base=base)
    if args.cli:
        run_cli(engine)
    else:
        build_ui(engine).queue().launch(server_name=args.host, server_port=args.port, share=args.share)


if __name__ == "__main__":
    main()
